"""DOCX, PDF and CSV export builders for every tool output."""
from __future__ import annotations

import csv
import io
import re
from datetime import date, datetime
from typing import Any, Iterable

ACCENT = (0x1B, 0x3A, 0x5F)


def _new_document(margin_left: float = 1.15):
    from docx import Document
    from docx.shared import Inches, Pt

    document = Document()
    for section in document.sections:
        section.top_margin = Inches(0.9)
        section.bottom_margin = Inches(0.9)
        section.left_margin = Inches(margin_left)
        section.right_margin = Inches(1.0)

    normal = document.styles["Normal"]
    normal.font.name = "Georgia"
    normal.font.size = Pt(11)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.25
    return document


def _centre(paragraph) -> None:
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER


def _title(document, text: str, subtitle: str = "") -> None:
    from docx.shared import Pt, RGBColor

    heading = document.add_paragraph()
    run = heading.add_run(text.upper())
    run.bold = True
    run.font.size = Pt(16)
    run.font.color.rgb = RGBColor(*ACCENT)
    _centre(heading)

    if subtitle:
        sub = document.add_paragraph()
        sub_run = sub.add_run(subtitle)
        sub_run.italic = True
        sub_run.font.size = Pt(11)
        _centre(sub)

    rule = document.add_paragraph()
    rule_run = rule.add_run("_" * 62)
    rule_run.font.color.rgb = RGBColor(0xC0, 0xC6, 0xCE)
    _centre(rule)


def _section_heading(document, text: str) -> None:
    from docx.shared import Pt, RGBColor

    paragraph = document.add_paragraph()
    paragraph.paragraph_format.space_before = Pt(14)
    run = paragraph.add_run(text.upper())
    run.bold = True
    run.font.size = Pt(12)
    run.font.color.rgb = RGBColor(*ACCENT)


def _footer(document, note: str = "") -> None:
    from docx.shared import Pt, RGBColor

    document.add_paragraph()
    paragraph = document.add_paragraph()
    stamp = datetime.now().strftime("%d %B %Y at %H:%M")
    text = f"Generated by LitigatAI on {stamp}."
    if note:
        text = f"{text} {note}"
    run = paragraph.add_run(text)
    run.italic = True
    run.font.size = Pt(8.5)
    run.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)

    disclaimer = document.add_paragraph()
    disclaimer_run = disclaimer.add_run(
        "AI generated draft. Verify every citation and every fact before filing."
    )
    disclaimer_run.italic = True
    disclaimer_run.font.size = Pt(8.5)
    disclaimer_run.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)


def _save(document) -> bytes:
    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()


def _write_body(document, content: str) -> None:
    """Render drafted text, honouring simple markdown emphasis and headings."""
    from docx.shared import Pt

    for raw_line in content.replace("\r\n", "\n").split("\n"):
        line = raw_line.rstrip()
        if not line.strip():
            spacer = document.add_paragraph()
            spacer.paragraph_format.space_after = Pt(2)
            continue

        stripped = line.strip()
        heading_match = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if heading_match:
            _section_heading(document, heading_match.group(2))
            continue

        is_heading = (
            stripped.isupper()
            and len(stripped) < 90
            and not stripped.startswith(("1.", "2.", "3.", "-"))
        )
        paragraph = document.add_paragraph()
        indent = len(line) - len(line.lstrip())
        if indent >= 3:
            from docx.shared import Inches

            paragraph.paragraph_format.left_indent = Inches(0.3)

        for segment, bold in _emphasis_segments(stripped):
            run = paragraph.add_run(segment)
            run.bold = bold or is_heading


def _emphasis_segments(text: str) -> Iterable[tuple[str, bool]]:
    parts = re.split(r"(\*\*[^*]+\*\*)", text)
    for part in parts:
        if not part:
            continue
        if part.startswith("**") and part.endswith("**") and len(part) > 4:
            yield part[2:-2], True
        else:
            yield part, False


def _table(document, headers: list[str], rows: list[list[str]], widths: list[float] | None = None):
    from docx.shared import Inches, Pt, RGBColor

    table = document.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    header_cells = table.rows[0].cells
    for index, header in enumerate(headers):
        header_cells[index].text = ""
        run = header_cells[index].paragraphs[0].add_run(header)
        run.bold = True
        run.font.size = Pt(10)
        run.font.color.rgb = RGBColor(*ACCENT)

    for row in rows:
        cells = table.add_row().cells
        for index, value in enumerate(row):
            cells[index].text = ""
            run = cells[index].paragraphs[0].add_run(str(value or ""))
            run.font.size = Pt(10)

    if widths:
        for row in table.rows:
            for index, width in enumerate(widths):
                if index < len(row.cells):
                    row.cells[index].width = Inches(width)
    return table


