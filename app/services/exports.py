def list_of_dates_docx(rows: list[dict], case_title: str = "") -> bytes:
    document = _new_document()
    _title(document, "List of Dates and Events", case_title)
    _table(
        document,
        ["Date", "Event", "Source", "Legal significance"],
        [
            [
                row.get("date", ""),
                row.get("event", ""),
                row.get("source", ""),
                row.get("significance", ""),
            ]
            for row in rows
        ],
        widths=[1.1, 2.5, 1.2, 1.7],
    )
    _footer(document, f"{len(rows)} events extracted.")
    return _save(document)


def list_of_dates_csv(rows: list[dict]) -> bytes:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(["Date", "Event", "Source", "Legal significance"])
    for row in rows:
        writer.writerow(
            [
                row.get("date", ""),
                row.get("event", ""),
                row.get("source", ""),
                row.get("significance", ""),
            ]
        )
    return buffer.getvalue().encode("utf-8-sig")


def judgment_brief_docx(brief: dict, case_name: str = "") -> bytes:
    document = _new_document()
    details = brief.get("case_details") or {}
    _title(document, "Judgment Brief", case_name or details.get("case_name", ""))

    meta_rows = [
        ["Case", details.get("case_name", "")],
        ["Citation", details.get("citation", "")],
        ["Court", details.get("court", "")],
        ["Bench", details.get("bench", "")],
        ["Date of judgment", details.get("date_of_judgment", "")],
        ["Subject matter", details.get("subject_matter", "")],
    ]
    _table(document, ["Field", "Detail"], [r for r in meta_rows if r[1]], widths=[1.6, 4.4])

    sections = [
        ("Facts", "facts"),
        ("Issues framed", "issues"),
        ("Arguments for the petitioner", "petitioner_arguments"),
        ("Arguments for the respondent", "respondent_arguments"),
        ("Held", "held"),
        ("Ratio decidendi", "ratio"),
        ("Significance and precedent value", "significance"),
        ("Key statutes cited", "key_statutes_cited"),
        ("Key cases cited", "key_cases_cited"),
    ]
    for heading, key in sections:
        content = brief.get(key)
        if not content:
            continue
        _section_heading(document, heading)
        if isinstance(content, list):
            for item in content:
                document.add_paragraph(str(item), style="List Bullet")
        else:
            _write_body(document, str(content))

    _footer(document)
    return _save(document)


def legal_document_docx(
    doc_type: str,
    content: str,
    *,
    case_title: str = "",
    court: str = "",
) -> bytes:
    document = _new_document(margin_left=1.4)
    if court:
        heading = document.add_paragraph()
        run = heading.add_run(f"IN THE {court.upper()}")
        run.bold = True
        _centre(heading)
    _title(document, doc_type, case_title)
    _write_body(document, content)
    _footer(document)
    return _save(document)


def research_answer_docx(question: str, answer: str, sources: list[dict] | None = None) -> bytes:
    document = _new_document()
    _title(document, "Legal Research Note", "")
    _section_heading(document, "Question")
    document.add_paragraph(question)
    _section_heading(document, "Answer")
    _write_body(document, answer)
    if sources:
        _section_heading(document, "Sources retrieved")
        for source in sources:
            citation = source.get("citation") or ""
            suffix = f" [{citation}]" if citation else ""
            document.add_paragraph(
                f"[{source.get('n', '')}] {source.get('title', '')}{suffix}",
                style="List Bullet",
            )
    _footer(document)
    return _save(document)


def authority_report_docx(result: dict) -> bytes:
    document = _new_document()
    _title(document, "Authority Check Report", result.get("citation_searched", ""))
    _table(
        document,
        ["Field", "Detail"],
        [
            ["Status", result.get("status", "UNKNOWN")],
            ["Confidence", result.get("confidence", "LOW")],
            ["Citation searched", result.get("citation_searched", "")],
        ],
        widths=[1.6, 4.4],
    )
    _section_heading(document, "Summary")
    _write_body(document, result.get("summary", ""))

    citing = result.get("citing_cases") or []
    if citing:
        _section_heading(document, f"Citing cases ({len(citing)})")
        _table(
            document,
            ["Case", "Treatment", "Excerpt"],
            [
                [c.get("case_name", ""), c.get("treatment", ""), c.get("excerpt", "")]
                for c in citing
            ],
            widths=[1.9, 1.2, 3.0],
        )
    _footer(document)
    return _save(document)


def translation_docx(
    original: str, translated: str, *, language: str = "", filename: str = ""
) -> bytes:
    document = _new_document()
    _title(document, "Translated Legal Document", filename)
    if language:
        document.add_paragraph(f"Source language detected: {language}")
    if translated:
        _section_heading(document, "English translation")
        _write_body(document, translated)
    _section_heading(document, "Original extracted text")
    _write_body(document, original)
    _footer(document)
    return _save(document)


def counter_arguments_docx(counters: list[dict], case_title: str = "") -> bytes:
    document = _new_document()
    _title(document, "Counter Argument Analysis", case_title)
    for counter in counters:
        _section_heading(
            document, f"Claim {counter.get('claim_id', '')}: response"
        )
        document.add_paragraph(f"Opposing claim: {counter.get('original_claim', '')}")
        _write_body(document, counter.get("counter_argument", ""))
        if counter.get("legal_basis"):
            document.add_paragraph(f"Legal basis: {counter['legal_basis']}")
        for citation in counter.get("citations", []) or []:
            document.add_paragraph(
                f"{citation.get('source', '')}: {citation.get('relevance', '')}",
                style="List Bullet",
            )
        if counter.get("strategy_note"):
            document.add_paragraph(f"Strategy: {counter['strategy_note']}")
    _footer(document)
    return _save(document)


def plain_docx(title: str, body: str, subtitle: str = "") -> bytes:
    document = _new_document()
    _title(document, title, subtitle)
    _write_body(document, body)
    _footer(document)
    return _save(document)


def cases_csv(cases: list[dict]) -> bytes:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(
        ["Case name", "Court", "Case number", "CNR", "Parties", "Status", "Next hearing", "Notes"]
    )
    for case in cases:
        writer.writerow(
            [
                case.get("case_name", ""),
                case.get("court", ""),
                case.get("case_number", ""),
                case.get("cnr_number", ""),
                case.get("parties", ""),
                case.get("status", ""),
                case.get("next_date", ""),
                case.get("notes", ""),
            ]
        )
    return buffer.getvalue().encode("utf-8-sig")


def pdf_from_text(title: str, body: str, subtitle: str = "") -> bytes:
    """Simple, clean PDF rendering used by the download menus."""
    from reportlab.lib.enums import TA_CENTER
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.lib.colors import HexColor
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    buffer = io.BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=22 * mm,
        rightMargin=18 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm,
        title=title,
    )
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Title"],
        fontName="Times-Bold",
        fontSize=16,
        textColor=HexColor("#1B3A5F"),
        alignment=TA_CENTER,
        spaceAfter=6,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Times-Italic",
        fontSize=10.5,
        alignment=TA_CENTER,
        textColor=HexColor("#4B5563"),
        spaceAfter=14,
    )
    body_style = ParagraphStyle(
        "DocBody",
        parent=styles["Normal"],
        fontName="Times-Roman",
        fontSize=11,
        leading=16,
        spaceAfter=7,
    )
    heading_style = ParagraphStyle(
        "DocHeading",
        parent=body_style,
        fontName="Times-Bold",
        fontSize=12,
        textColor=HexColor("#1B3A5F"),
        spaceBefore=12,
        spaceAfter=5,
    )
    footer_style = ParagraphStyle(
        "DocFooter",
        parent=body_style,
        fontSize=8.5,
        textColor=HexColor("#6B7280"),
    )

    def esc(value: str) -> str:
        return (
            value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        )

    flow: list[Any] = [Paragraph(esc(title.upper()), title_style)]
    if subtitle:
        flow.append(Paragraph(esc(subtitle), subtitle_style))
    flow.append(Spacer(1, 4))

    for raw_line in body.replace("\r\n", "\n").split("\n"):
        line = raw_line.strip()
        if not line:
            flow.append(Spacer(1, 5))
            continue
        heading_match = re.match(r"^(#{1,6})\s+(.*)$", line)
        if heading_match:
            flow.append(Paragraph(esc(heading_match.group(2)), heading_style))
            continue
        rendered = esc(line)
        rendered = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", rendered)
        rendered = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<i>\1</i>", rendered)
        style = heading_style if line.isupper() and len(line) < 90 else body_style
        flow.append(Paragraph(rendered, style))

    flow.append(Spacer(1, 12))
    stamp = datetime.now().strftime("%d %B %Y")
    flow.append(
        Paragraph(
            f"Generated by LitigatAI on {stamp}. AI generated draft. "
            "Verify every citation before filing.",
            footer_style,
        )
    )
    document.build(flow)
    return buffer.getvalue()


def safe_filename(stem: str, extension: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "_", (stem or "litigatai").strip())
    cleaned = re.sub(r"_+", "_", cleaned).strip("_") or "litigatai"
    return f"{cleaned[:70]}_{date.today().isoformat()}.{extension}"
